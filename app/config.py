# ---------------------------------------------------------------- 节拍检测
# 「多频带投票 + 能量终审」（借鉴 run_beats 的做法，2026-09-22 重构）：
#
# 旧方案的坑：用「数起音事件」的 F1 给候选打分，其中召回率的分母是**全部起音数**。
#   一拍里往往有好几个起音（底鼓 + 军鼓 + hi-hat 各算一个），起音数远多于拍数，
#   于是真 BPM 网格的召回率被天然压低 —— 实测一首 99.4 BPM 的歌被改判成 198.8
#   （起音 593 个 vs 真拍 262 个，99 网格召回率上限只有 44%）。根子是「起音 ≠ 拍」。
#
# 新方案三步，对应 run_beats 反编译出的 luke.audio.a.{d,c,e}：
#   ① 多频带独立检测：STFT 拆成 14 个频带（边界照抄竞品的 30Hz 梯度，截至 Nyquist），
#      每带独立做归一化自相关测 BPM —— 低频底鼓带、中频人声带、高频 hi-hat 带各测各的。
#   ② 折叠投票：每个候选先折叠到 120 附近（2^k 倍中取最近的），再按 1% 容差跨带聚类
#      数票。真节拍会在多数频带胜出；某一带被骗了，别的带能把它投下去。
#   ③ 能量终审：候选各铺一条网格、搜相位，比「网格点处起音包络的**均值**」。
#      用均值不用总和 —— 总和会让点数多一倍的候选白占便宜（密度偏置换个马甲回来）。
#      真值网格每点都踩在峰上，均值自然最高；半速网格一半落空、倍速网格摊薄强弱拍。
BPM_LO = 60.0                           # 投票与候选的 BPM 下限（照抄竞品）
# 上限放宽到 200（竞品是 180）：RunBeat 的用户常传 175~190 的歌 —— 真值 184.6
# 的歌折叠投票会聚到 92.3，2 倍候选 184.6 若被 180 拦住就永远进不了终审候选池，
# 只能报 92.3（实测踩过）。防倍速误判交给终审打分（总和 ÷ √点数），不靠硬卡区间。
BPM_HI = 200.0
BAND_N_FFT = 2048                       # 多频带用的 STFT 窗长（竞品同款）
# 频带边界（Hz），竞品原表是 0~20000 的 30Hz 梯度，这里截到 ANALYSIS_SR 的 Nyquist。
# 相邻边界两两相接（30,30 / 60,60...）是竞品原表的写法，去重后 14 个实带。
BAND_EDGES_HZ = (0, 30, 60, 100, 150, 250, 400, 600, 1000, 1600, 2500, 3500, 5000, 8000, 11025)
# 静带过滤：原始能量 std 低于最大带的这个比例的带不参与投票。合成音 / 极简编曲
# 里大量频带是数值噪声，z-score 会把噪声放大成等权票（实测 13 个噪声带把
# 真值 150 的票压没了，投出 120.2），必须先掐掉。
BAND_MIN_STD_RATIO = 0.05
VOTE_TOL = 0.02                         # 聚类容差：BPM 相差 2% 以内算同一票。竞品用 1%，
                                        # 但 lag 只能取整数帧，60fps 帧率下 150 BPM 附近的
                                        # 量化误差就有 ±1.5% —— 1% 会把真值的票拆散（实测
                                        # 149.8 和 152.0 被拆成两簇各 1 票，被伪峰挤出 top2）
JUDGE_MARGIN = 1.03                     # 挑战者要赢过投票 top1 这么多倍才改判。宁可漏改，不要改坏
# 倍频关系的改判门槛更高：挑战者与 base 恰好差 2 倍 / 半速时（「99.4 被推成
# 198.8」的形态），1.03 太松 —— 只要挑战侧的带里有半拍切分律动就能凑够。
# 等强拍下真值对半速的折中分优势是 √2 ≈ 1.414，门槛取 1.15 卡在两者之间。
JUDGE_OCTAVE_MARGIN = 1.15
# 终审打分 = 「网格点包络 sum/√点数」×「精确率因子(0.25 + 0.75×精确率)」。
#   sum/√点数：等强拍下真值（点数多的一侧）以 √2 优势胜出（半速读法点少一半）；
#   精确率 = 网格点踩中**离散起音**的比例（tol = 周期×0.2，上限 50ms）。它专治
#   两类冒牌候选：① 倍频误读 —— 302ms 网格一半点落在起音空档（实测真值 99.4
#   的歌精确率 0.80 vs 198.8 只有 0.12）；② 杂乱律动（132.5 之类切分周期）——
#   网格点与起音对不上。用精确率不用 F1：召回率的分母是全部起音数，一拍多个
#   起音时真值召回率被天然压低 —— 那正是旧裁决（F1）翻车的根源，见下。
#   0.25 的软底防止起音检测整体失灵时分数全零。
JUDGE_PREC_TOL_RATIO = 0.20             # 「踩中了」的判定半径，取周期的比例
JUDGE_PREC_TOL_SEC = 0.05               # 判定半径绝对上限（秒）
JUDGE_PREC_FLOOR = 0.25                 # 精确率因子的软底
JUDGE_WIN = 2                           # 终审打分时网格点左右各看几帧取最大（对齐误差容忍，竞品同款）
FOLD_CENTER = 120.0                     # 折叠目标：2^k 倍里取离它最近的

# 「均匀网格」：拍点走**严格等间隔**的网格，间隔取自 DP 拍点拟合出的精确周期。
#
# 为什么不做逐点吸附（曾经做过，已废弃）：吸附为了贴某个鼓点会改变相邻间隔，
#   实测把间隔 CV 从 2.8% 拉到 4.9%、max 从 380ms 拉到 454ms —— 跟着跑的节拍
#   要的是稳，忽快忽慢比落不准更难受。而且它连自己的目标都没达成（贴合度反而
#   从 3.88x 掉到 3.68x），因为 beat_track 的 DP 本来就把拍点放在起音上了。
#
# 为什么周期必须拟合、不能直接用 beat_track 的 tempo：那个 tempo 是量化过的
#   （只能落在 60*sr/(hop*L) 的网格上），《漂移》实测差 0.76%，用它在 4 分钟
#   的歌上铺网格，到曲末已经漂了 1.8 秒 —— 网格后半段和鼓点完全错开
#   （贴合度从 3.77x 掉到 1.06x，等于随机落点）。
GRID_PHASES = 720                       # 相位搜索步数，精度 = 周期/720
GRID_FIT_SIGMA = 2.0                    # 拟合时剔除残差超过这个标准差的拍点
GRID_FIT_ROUNDS = 3                     # 迭代剔除轮数（应对漏拍 / 跳拍把斜率带偏）

